// Command errgen reads the business codes of an IDL repository's errors/
// directory (one Thrift file per domain, `const i32 Name = code` with the
// message as the comment line above) and writes, next to the constants kitex
// generated, a Go file with the messages:
//
//	errcode.Message(code) string   the message of a code ("" when unknown)
//	errcode.Err(code) error        kerrors.NewBizStatusError(code, Message(code))
//	errcode.Errf(code, detail)     the same with a detail appended: "会员不存在：uid 7"
//
// A service answers errcode.Err(errcode.MemberNotFound) and never writes the
// message by hand, so the gateway and the front end show the one sentence
// the IDL declares. `make gen` runs it after kitex:
//
//	go run github.com/sezznaw/devkit-common/cmd/errgen -dir ../idl/errors -out kitex_gen/errcode
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var errConst = regexp.MustCompile(`^\s*const\s+i32\s+(\w+)\s*=\s*(\d+)`)

type entry struct {
	code    int
	name    string
	message string
}

func main() {
	dir := flag.String("dir", "", "the IDL repository's errors/ directory")
	out := flag.String("out", "", "the errcode package directory kitex generated (kitex_gen/errcode)")
	flag.Parse()
	if *dir == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "errgen: -dir and -out are required")
		os.Exit(2)
	}
	entries, err := read(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "errgen:", err)
		os.Exit(1)
	}
	if len(entries) == 0 {
		return // no codes declared yet: nothing to write
	}
	src, err := render(entries)
	if err != nil {
		fmt.Fprintln(os.Stderr, "errgen:", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "errgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(*out, "zz_messages.go"), src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "errgen:", err)
		os.Exit(1)
	}
}

func read(dir string) ([]entry, error) {
	files, _ := filepath.Glob(filepath.Join(dir, "*.thrift"))
	sort.Strings(files)
	var out []entry
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		lines := strings.Split(string(b), "\n")
		for i, line := range lines {
			m := errConst.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			code, _ := strconv.Atoi(m[2])
			msg := ""
			if i > 0 {
				prev := strings.TrimSpace(lines[i-1])
				if strings.HasPrefix(prev, "//") {
					msg = strings.TrimSpace(strings.TrimPrefix(prev, "//"))
				}
			}
			out = append(out, entry{code, m[1], msg})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].code < out[j].code })
	return out, nil
}

func render(entries []entry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by devkit-common/cmd/errgen from idl/errors/*.thrift. DO NOT EDIT.\n\n")
	b.WriteString("package errcode\n\nimport \"github.com/cloudwego/kitex/pkg/kerrors\"\n\n")
	b.WriteString("// messages is the comment above each code in idl/errors/*.thrift.\nvar messages = map[int32]string{\n")
	for _, e := range entries {
		b.WriteString(fmt.Sprintf("\t%s: %s,\n", e.name, strconv.Quote(e.message)))
	}
	b.WriteString("}\n\n")
	b.WriteString(`// Message is the message the IDL declares for code; "" when the code is not declared.
func Message(code int32) string { return messages[code] }

// Err is the business error of code with the IDL's message: what a service
// returns (the gateway turns it into {code, msg}).
func Err(code int32) error { return kerrors.NewBizStatusError(code, Message(code)) }

// Errf is Err with a detail for the caller, appended after a colon:
// "会员不存在：uid 7". The detail is for people; never put secrets in it.
func Errf(code int32, detail string) error {
	if detail == "" {
		return Err(code)
	}
	return kerrors.NewBizStatusError(code, Message(code)+"："+detail)
}
`)
	return format.Source(b.Bytes())
}
