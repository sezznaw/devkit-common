func TestAnnotateOnlyBareStructFields(t *testing.T) {
	in := `namespace go x
struct Req {
    1: i64 uid (api.body="uid")
    2: string name // comment
    3: optional list<string> tags,
}
service S {
    Resp Do(1: Req req) (api.post="/v1/x")
}
`
	out := string(Annotate([]byte(in)))
	for _, want := range []string{`1: i64 uid (api.body="uid")`, `2: string name (api.body="name")  // comment`, `3: optional list<string> tags (api.body="tags"),`, `Resp Do(1: Req req) (api.post="/v1/x")`} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
}

