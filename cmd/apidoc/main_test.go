func TestLocalize(t *testing.T) {
	src := []byte("// @docs title: 玩家网关\n// @docs description: 所有接口。\n// @docs tag member: 会员\n// @docs tag wallet: 钱包\nnamespace go x\n")
	d := ParseDirectives(src)
	if d.Title != "玩家网关" || d.Description != "所有接口。" || len(d.Tags) != 2 || d.Tags[1].Name != "钱包" {
		t.Fatalf("%+v", d)
	}
	doc := `openapi: 3.0.3
info:
  title: x
  version: "1"
paths:
  /ping:
    get:
      tags: [SerApiService]
      operationId: Ping
      responses:
        "200":
          description: Successful response
  /v1/member/getProfile:
    post:
      tags: [SerApiService]
      description: 取会员资料。网关调 ser-user。
      operationId: GetProfile
      responses: {}
  /v1/wallet/balance:
    post:
      tags: [SerApiService]
      operationId: Balance
      responses: {}
`
	out, err := Patch([]byte(doc), d.Title, "v1", d.Description, "x", d, map[string]bool{"Ping": true}, nil, nil, nil, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{"title: 玩家网关", "description: 所有接口。", "summary: 取会员资料", "description: 网关调 ser-user。", "- 会员", "- 钱包", "- 系统", "description: 成功。"} {
		if !strings.Contains(s, want) {
			t.Errorf("missing %q in:\n%s", want, s)
		}
	}
	if strings.Contains(s, "SerApiService") || strings.Contains(s, "Successful response") {
		t.Errorf("english placeholders left:\n%s", s)
	}
	top := s[strings.LastIndex(s, "\ntags:"):]
	if i, j, k := strings.Index(top, "name: 会员"), strings.Index(top, "name: 钱包"), strings.Index(top, "name: 系统"); !(i >= 0 && i < j && j < k) {
		t.Errorf("tag order: directives first, then the rest\n%s", top)
	}
}

func TestPublicMethodsAndSecurity(t *testing.T) {
	src := []byte(`service S {
    // 登录。
    // @public
    LoginResp Login(1: LoginReq req) (api.post="/v1/auth/login")
    // 取资料。
    ProfileResp GetProfile(1: ProfileReq req) (api.post="/v1/member/getProfile")
}`)
	pub := PublicMethods(src)
	if !pub["Login"] || pub["GetProfile"] {
		t.Fatalf("%v", pub)
	}
	doc := "openapi: 3.0.3\ninfo:\n  title: x\n  version: '1'\npaths:\n  /v1/auth/login:\n    post:\n      operationId: S_Login\n      responses: {}\n  /v1/member/getProfile:\n    post:\n      operationId: S_GetProfile\n      responses: {}\n"
	out, err := Patch([]byte(doc), "x", "1", "", "x", Directives{}, pub, nil, nil, nil, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	if !strings.Contains(s, "securitySchemes") || !strings.Contains(s, "bearerAuth") {
		t.Errorf("scheme missing:\n%s", s)
	}
	login := s[strings.Index(s, "/v1/auth/login"):strings.Index(s, "/v1/member/getProfile")]
	if !strings.Contains(login, "security: []") {
		t.Errorf("login is public:\n%s", login)
	}
	profile := s[strings.Index(s, "/v1/member/getProfile"):strings.Index(s, "components:")]
	if !strings.Contains(profile, "- bearerAuth: []") {
		t.Errorf("profile requires bearer:\n%s", profile)
	}
}

func TestSplitSummaryDropsDirectives(t *testing.T) {
	cases := []struct{ in, summary, rest string }{
		{"登录。账号或密码错误 2003。\n@public", "登录", "账号或密码错误 2003。"},
		{"登出。结束当前会话。", "登出", "结束当前会话。"},
		{"健康检查。返回 pong: <message>。\n@public", "健康检查", "返回 pong: <message>。"},
		{"取资料\n第二行说明", "取资料", "第二行说明"},
		{"@public", "", ""},
		{"只有标题。", "只有标题", ""},
		{"角色列表。\n@perm role.view", "角色列表", ""},
		{"Ping.", "Ping", ""},
	}
	for _, c := range cases {
		s, r := splitSummary(c.in)
		if s != c.summary || r != c.rest {
			t.Errorf("%q: got (%q, %q), want (%q, %q)", c.in, s, r, c.summary, c.rest)
		}
	}
}

func TestPermMethods(t *testing.T) {
	src := []byte("service S {\n    // 管理员列表\n    // @perm admin.view\n    ListResp AdminList(1: ListReq req) (api.post=\"/v1/admin/list\")\n    // 当前登录\n    MeResp AuthMe(1: MeReq req) (api.post=\"/v1/auth/me\")\n}\n")
	got := PermMethods(src)
	if len(got) != 1 || got["AdminList"] != "admin.view" {
		t.Fatalf("%v", got)
	}
	// A qualified return type (common.Empty: a method that returns nothing)
	// is a method too; its directives were silently dropped before v0.55.1.
	qualified := []byte("service S {\n    // 删角色\n    // @perm role.manage\n    common.Empty Delete(1: DeleteReq req) (api.post=\"/v1/role/delete\")\n    // 重置密码\n    // @public\n    // @limit 10/m\n    common.Empty Reset(1: ResetReq req) (api.post=\"/v1/auth/reset\")\n}\n")
	if p := PermMethods(qualified); len(p) != 1 || p["Delete"] != "role.manage" {
		t.Fatalf("perm on a common.Empty method: %v", p)
	}
	if pub := PublicMethods(qualified); !pub["Reset"] || pub["Delete"] {
		t.Fatalf("public on a common.Empty method: %v", pub)
	}
	if l := LimitMethods(qualified); l["Reset"] != "10/m" {
		t.Fatalf("limit on a common.Empty method: %v", l)
	}
	doc := "openapi: 3.0.3\ninfo:\n  title: x\n  version: '1'\npaths:\n  /v1/admin/list:\n    post:\n      operationId: S_AdminList\n      responses: {}\n  /v1/auth/me:\n    post:\n      operationId: S_AuthMe\n      responses: {}\n"
	out, err := Patch([]byte(doc), "", "", "", "x", Directives{}, nil, got, nil, nil, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out), "x-permission: admin.view") || strings.Count(string(out), "x-permission") != 1 {
		t.Fatalf("%s", out)
	}
}

func TestEnvelope(t *testing.T) {
	doc := "openapi: 3.0.3\ninfo:\n  title: x\n  version: '1'\npaths:\n  /v1/a:\n    post:\n      operationId: S_A\n      responses:\n        \"200\":\n          description: ok\n          content:\n            application/json:\n              schema:\n                $ref: '#/components/schemas/ProfileBody'\n  /v1/b:\n    post:\n      operationId: S_B\n      responses: {}\n"
	out, err := Patch([]byte(doc), "x", "1", "", "x", Directives{}, nil, nil, nil, nil, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{"code:", "msg:", "data:", "ProfileBody", "required:"} {
		if !strings.Contains(s, want) {
			t.Fatalf("missing %q in\n%s", want, s)
		}
	}
	// /v1/b returns Empty: the envelope has no data, and the status key is a string.
	b := s[strings.Index(s, "/v1/b"):]
	if strings.Contains(b, "data:") {
		t.Fatalf("Empty response documents data:\n%s", b)
	}
	if !strings.Contains(b, `"200":`) {
		t.Fatalf("status key must be the string \"200\":\n%s", b)
	}
}

func TestMergeAndPrefix(t *testing.T) {
	a := "openapi: 3.0.3\npaths:\n  /v1/member/list:\n    post:\n      operationId: MemberService_List\n      responses:\n        \"200\":\n          content:\n            application/json:\n              schema:\n                $ref: '#/components/schemas/ListRespBody'\ncomponents:\n  schemas:\n    ListRespBody:\n      type: object\ntags:\n  - name: 会员\n"
	b := "openapi: 3.0.3\npaths:\n  /v1/wallet/list:\n    post:\n      operationId: WalletService_List\n      responses:\n        \"200\":\n          content:\n            application/json:\n              schema:\n                $ref: '#/components/schemas/ListRespBody'\ncomponents:\n  schemas:\n    ListRespBody:\n      type: string\ntags:\n  - name: 钱包\n  - name: 会员\n"
	var ra, rb yaml.Node
	if err := yaml.Unmarshal([]byte(a), &ra); err != nil {
		t.Fatal(err)
	}
	if err := yaml.Unmarshal([]byte(b), &rb); err != nil {
		t.Fatal(err)
	}
	prefixSchemas(ra.Content[0], "member")
	prefixSchemas(rb.Content[0], "wallet")
	if err := mergeDoc(ra.Content[0], rb.Content[0], "wallet.thrift"); err != nil {
		t.Fatal(err)
	}
	out, _ := yaml.Marshal(&ra)
	s := string(out)
	for _, want := range []string{"member.ListRespBody:", "wallet.ListRespBody:", "'#/components/schemas/member.ListRespBody'", "'#/components/schemas/wallet.ListRespBody'", "/v1/member/list", "/v1/wallet/list", "name: 钱包"} {
		if !strings.Contains(s, want) {
			t.Fatalf("missing %q in\n%s", want, s)
		}
	}
	if strings.Count(s, "name: 会员") != 1 {
		t.Fatalf("tag 会员 should appear once:\n%s", s)
	}
	// the same route in two domains is refused
	var rc yaml.Node
	_ = yaml.Unmarshal([]byte(b), &rc)
	if err := mergeDoc(ra.Content[0], rc.Content[0], "again.thrift"); err == nil {
		t.Fatal("duplicate route accepted")
	}
}

func TestErrorCodes(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "member.thrift"), []byte("namespace go errcode\n\n// 会员不存在\nconst i32 MemberNotFound = 2001\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "common.thrift"), []byte("namespace go errcode\n\n// 参数错误\nconst i32 BadParam = 1001\n"), 0o644)
	seq := errorCodes(dir)
	if seq == nil || len(seq.Content) != 2 {
		t.Fatalf("got %+v", seq)
	}
	out, _ := yaml.Marshal(seq)
	s := string(out)
	if !strings.Contains(s, "code: 1001") || !strings.Contains(s, "name: MemberNotFound") || !strings.Contains(s, "message: 会员不存在") || !strings.Contains(s, "domain: member") {
		t.Fatalf("%s", s)
	}
	if strings.Index(s, "1001") > strings.Index(s, "2001") {
		t.Fatalf("not sorted:\n%s", s)
	}
}

func TestRequired(t *testing.T) {
	dir := t.TempDir()
	os.MkdirAll(filepath.Join(dir, "member"), 0o755)
	os.WriteFile(filepath.Join(dir, "member", "member.thrift"), []byte("namespace go member\n\nstruct MemberInfo {\n    1: i64 uid\n    2: string username\n    3: optional i32 status\n}\nstruct Empty {}\n"), 0o644)
	structs := requiredFields(dir)
	if got := structs["member.MemberInfo"]; len(got) != 2 || got[0] != "uid" || got[1] != "username" {
		t.Fatalf("required = %v", got)
	}
	doc := "openapi: 3.0.3\ncomponents:\n  schemas:\n    member.MemberInfoBody:\n      type: object\n      properties:\n        uid: {type: integer}\n        username: {type: string}\n        status: {type: integer}\n    member.Empty:\n      type: object\n"
	var root yaml.Node
	if err := yaml.Unmarshal([]byte(doc), &root); err != nil {
		t.Fatal(err)
	}
	Required(root.Content[0], structs)
	out, _ := yaml.Marshal(&root)
	s := string(out)
	if !strings.Contains(s, "required:") || !strings.Contains(s, "- uid") || !strings.Contains(s, "- username") || strings.Contains(s, "- status") {
		t.Fatalf("%s", s)
	}
}

