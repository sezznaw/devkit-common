// A gateway's IDL is a directory: one Thrift file per domain (its own
// namespace, its own service; hz makes one handler package of each) and,
// optionally, a file with only `// @docs` lines for the page's title and
// description. runDir documents the directory as one page: every file with
// a service goes through the plugin and the patches on its own (so two
// domains may both have a `List` method), schema names get the domain as a
// prefix (two domains may both have a `ListReq`), and the results are
// merged: one paths map, one components map, one tag list.
func runDir(dir, out, title, version, desc string) error {
	if err := needTools(); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	var files []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".thrift") {
			files = append(files, e.Name())
		}
	}
	sort.Strings(files)
	if len(files) == 0 {
		return fmt.Errorf("%s has no .thrift file", dir)
	}
	tmp, work, err := stage(dir)
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)

	// Directives from every file: the docs-only file names the page, a
	// domain file may name its own tag.
	var d Directives
	srcs := map[string][]byte{}
	for _, f := range files {
		src, err := os.ReadFile(filepath.Join(dir, f))
		if err != nil {
			return err
		}
		srcs[f] = src
		fd := ParseDirectives(src)
		if d.Title == "" {
			d.Title = fd.Title
		}
		if fd.Description != "" {
			if d.Description != "" {
				d.Description += "\n"
			}
			d.Description += fd.Description
		}
		d.Tags = append(d.Tags, fd.Tags...)
	}
	if title == "" {
		title = d.Title
	}
	if desc == "" {
		desc = d.Description
	}
	fallback := filepath.Base(dir)

	var master *yaml.Node
	for _, f := range files {
		src := srcs[f]
		if !serviceRE.Match(src) {
			continue // docs-only or structs-only file
		}
		doc, err := plugin(work, f)
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		patched, err := Patch(doc, title, version, desc, fallback, d, PublicMethods(src), PermMethods(src), AuditMethods(src), LimitMethods(src))
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		var root yaml.Node
		if err := yaml.Unmarshal(patched, &root); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		if ns := namespaceOf(src); ns != "" {
			prefixSchemas(root.Content[0], ns)
		}
		if master == nil {
			master = &root
			continue
		}
		if err := mergeDoc(master.Content[0], root.Content[0], f); err != nil {
			return err
		}
	}
	if master == nil {
		return fmt.Errorf("%s: no file declares a service", dir)
	}
	// Fields are present unless the IDL says optional: tell the front end.
	Required(master.Content[0], requiredFields(filepath.Dir(dir)))
	// The business codes, from the repository's errors/ directory (one Thrift
	// file per domain), so a front end generates its code table from the
	// same document it generates its types from.
	if codes := errorCodes(filepath.Join(filepath.Dir(dir), "errors")); codes != nil && len(codes.Content) > 0 {
		master.Content[0].Content = append(master.Content[0].Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "x-error-codes"}, codes)
	}
	b, err := yaml.Marshal(master)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, append([]byte("# Generated by `make gen` (devkit-common cmd/apidoc) from the service's IDL directory. Do not edit.\n"), b...), 0o644)
}

var (
	serviceRE   = regexp.MustCompile(`(?m)^\s*service\s+\w+`)
	namespaceRE = regexp.MustCompile(`(?m)^\s*namespace\s+go\s+([\w.]+)`)
)

func namespaceOf(src []byte) string {
	if m := namespaceRE.FindSubmatch(src); m != nil {
		return string(m[1])
	}
	return ""
}

func needTools() error {
	if _, err := exec.LookPath("thriftgo"); err != nil {
		return fmt.Errorf("thriftgo not found in PATH (run: make tools)")
	}
	if _, err := exec.LookPath("thrift-gen-http-swagger"); err != nil {
		return fmt.Errorf("thrift-gen-http-swagger not found in PATH (run: make tools)")
	}
	return nil
}

// stage copies the IDL repository (dir and its siblings: includes such as
// "../common/common.thrift" are relative) to a temporary directory with the
// annotations added, keeping the layout. It returns the temporary root and
// the copy of dir inside it.
func stage(dir string) (tmp, work string, err error) {
	tmp, err = os.MkdirTemp("", "apidoc-*")
	if err != nil {
		return "", "", err
	}
	repoDir := filepath.Dir(dir)
	work = filepath.Join(tmp, filepath.Base(dir))
	err = filepath.WalkDir(repoDir, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if e.IsDir() {
			if e.Name() == ".git" || e.Name() == "node_modules" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(e.Name(), ".thrift") {
			return nil
		}
		rel, err := filepath.Rel(repoDir, p)
		if err != nil {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		dst := filepath.Join(tmp, rel)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		return os.WriteFile(dst, Annotate(b), 0o644)
	})
	if err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}
	return tmp, work, nil
}

// plugin runs thriftgo with thrift-gen-http-swagger on one file of the
// staged directory and returns the openapi.yaml it wrote.
func plugin(work, file string) ([]byte, error) {
	outDir := filepath.Join(work, "out-"+strings.TrimSuffix(file, ".thrift"))
	cmd := exec.Command("thriftgo", "-g", "go", "-p", "http-swagger:OutputDir="+outDir, file)
	cmd.Dir = work
	if b, err := cmd.CombinedOutput(); err != nil {
		return nil, fmt.Errorf("thriftgo: %w\n%s", err, b)
	}
	doc, err := os.ReadFile(filepath.Join(outDir, "openapi.yaml"))
	if err != nil {
		return nil, fmt.Errorf("the plugin wrote no openapi.yaml: %w", err)
	}
	return doc, nil
}

// prefixSchemas renames every components.schemas entry of one domain's
// document to "<ns>.<Name>" and rewrites the $ref strings accordingly, so
// two domains can both declare a ListReq.
func prefixSchemas(top *yaml.Node, ns string) {
	comps := mapGet(top, "components")
	if comps == nil {
		return
	}
	schemas := mapGet(comps, "schemas")
	if schemas == nil {
		return
	}
	renamed := map[string]string{}
	for i := 0; i+1 < len(schemas.Content); i += 2 {
		k := schemas.Content[i]
		renamed["#/components/schemas/"+k.Value] = "#/components/schemas/" + ns + "." + k.Value
		k.Value = ns + "." + k.Value
	}
	var walk func(n *yaml.Node)
	walk = func(n *yaml.Node) {
		if n.Kind == yaml.ScalarNode {
			if v, ok := renamed[n.Value]; ok {
				n.Value = v
			}
			return
		}
		for _, c := range n.Content {
			walk(c)
		}
	}
	walk(top)
}

// mergeDoc adds the paths, schemas and tags of one domain's document to the
// master's. The same path and method in two domains is an error: the
// gateway could not route it either.
func mergeDoc(master, add *yaml.Node, file string) error {
	mp, ap := mapGet(master, "paths"), mapGet(add, "paths")
	if ap != nil {
		if mp == nil {
			mp = &yaml.Node{Kind: yaml.MappingNode}
			master.Content = append(master.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "paths"}, mp)
		}
		for i := 0; i+1 < len(ap.Content); i += 2 {
			path, ops := ap.Content[i], ap.Content[i+1]
			if existing := mapGet(mp, path.Value); existing != nil {
				for j := 0; j+1 < len(ops.Content); j += 2 {
					if mapGet(existing, ops.Content[j].Value) != nil {
						return fmt.Errorf("%s: %s %s is declared in another domain file too; one route belongs to one domain", file, strings.ToUpper(ops.Content[j].Value), path.Value)
					}
					existing.Content = append(existing.Content, ops.Content[j], ops.Content[j+1])
				}
				continue
			}
			mp.Content = append(mp.Content, path, ops)
		}
	}
	mc, ac := mapGet(master, "components"), mapGet(add, "components")
	if ac != nil {
		if mc == nil {
			mc = &yaml.Node{Kind: yaml.MappingNode}
			master.Content = append(master.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "components"}, mc)
		}
		for i := 0; i+1 < len(ac.Content); i += 2 {
			key, val := ac.Content[i], ac.Content[i+1]
			dst := mapGet(mc, key.Value)
			if dst == nil {
				mc.Content = append(mc.Content, key, val)
				continue
			}
			for j := 0; j+1 < len(val.Content); j += 2 {
				if mapGet(dst, val.Content[j].Value) == nil {
					dst.Content = append(dst.Content, val.Content[j], val.Content[j+1])
				}
			}
		}
	}
	mt, at := mapGet(master, "tags"), mapGet(add, "tags")
	if at != nil {
		if mt == nil {
			mt = &yaml.Node{Kind: yaml.SequenceNode}
			master.Content = append(master.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "tags"}, mt)
		}
		seen := map[string]bool{}
		for _, t := range mt.Content {
			if n := mapGet(t, "name"); n != nil {
				seen[n.Value] = true
			}
		}
		for _, t := range at.Content {
			if n := mapGet(t, "name"); n != nil && !seen[n.Value] {
				mt.Content = append(mt.Content, t)
				seen[n.Value] = true
			}
		}
	}
	return nil
}
